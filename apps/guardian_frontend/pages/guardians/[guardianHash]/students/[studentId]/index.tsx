import { SchoolStepTags } from '@cometa/trpc/src/admissions/types';
import { useEffect, useState } from 'react';
import { useSelectedSchool } from '~/stores/globalStore';

function StudentPage() {
  const router = useRouter();
  const selectedSchool = useSelectedSchool();
  const { guardianHash } = router.query;
  const studentId = router.query.studentId as string;

  const [enableConsentments, setEnableConsentments] = useState(false);

  const { data: student } = api.students.getStudent.useQuery({ studentId });
  const { data: form, isLoading: isLoadingForm } = api.forms.getDynamicForm.useQuery(
    { createdBy: student?.school_id, category: SchoolStepTags.ConsentForm, includeLayout: false },
    { enabled: !!student?.school_id }
  );

  const baseUrl = `/guardians/${guardianHash}/students/${studentId}`;
  const personalMenuItems: MenuItemProps[] = [
    {
      icon: 'personal',
      text: 'Datos del estudiante',
      href: `${baseUrl}/personal`,
    },
    {
      icon: 'contact',
      text: 'Detalles de contacto',
      href: `${baseUrl}/contact`,
    },
    {
      icon: 'guardians',
      text: 'Padres y tutores',
      href: `${baseUrl}/guardians`,
    },
  ];

  const additionalMenuItems: MenuItemProps[] = [
    {
      icon: 'evaluation_scores',
      text: 'Calificaciones',
      href: `${baseUrl}/scores`,
      enabled: !!selectedSchool?.config_portal?.enable_academic_access,
    },
    {
      icon: 'consentments',
      text: 'Consentimientos',
      href: `${baseUrl}/consentments`,
      enabled: enableConsentments,
    },
    {
      icon: 'medical',
      text: 'Información médica',
      href: `${baseUrl}/medical`,
    },
  ];

  const section =
    student?.section && student?.section?.grade
      ? `${student?.section?.grade} ${student?.section?.group} - ${student?.section?.level_name}`
      : '-';
  const enrollmentCode = student?.enrollment_code;

  useEffect(() => {
    if (!isLoadingForm) {
      setEnableConsentments(!!form);
    }
  }, [isLoadingForm, form]);

  return (
    <>
      <header className="py-6 text-white flex flex-col gap-6 bg-[#873aff] bg-[url('/header-bg.svg')] bg-no-repeat bg-right w-screen relative left-1/2 right-1/2 -mx-[50vw]">
        <Link href={`/guardians/${guardianHash}/students`} className="px-6 flex gap-3 items-center">
          <BackButton arrowColor="#873AFF" circleColor="white" />
          <span className="text-sm font-semibold uppercase">Volver</span>
        </Link>

        <div className="px-6 flex items-center gap-5">
          <div className="w-20 h-20">
            {student?.photo ? (
              <img
                src={student?.photo}
                alt={student?.first_name}
                className="w-full h-full rounded-full object-cover border-2 border-white"
              />
            ) : (
              <img
                src="/images/avatar.jpg"
                alt="Default avatar photo"
                className="w-full h-full rounded-full object-cover border-2 border-white"
              />
            )}
          </div>

          <div>
            <h3 className="text-lg font-bold">
              {student?.first_name} {student?.last_name}
            </h3>
            <p>{section}</p>
            {enrollmentCode ? <p>{enrollmentCode}</p> : null}
          </div>
        </div>
      </header>

      <section className="flex flex-col gap-6 px-5 py-6 bg-[#FBFCFD]">
        <div className="flex flex-col gap-2">
          <h4 className="text-xs font-semibold uppercase text-[#535765]">Información general</h4>
          <div className="flex flex-col border border-[#EBEDF0] rounded-xl overflow-hidden">
            {personalMenuItems.map((item) => (
              <MenuItem key={item.href} {...item} />
            ))}
          </div>
        </div>

        <div className="flex flex-col gap-2">
          <h4 className="text-xs font-semibold uppercase">Detalles adicionales</h4>
          <div className="flex flex-col border border-[#EBEDF0] rounded-xl overflow-hidden">
            {additionalMenuItems.map((item) => (
              <MenuItem key={item.href} {...item} />
            ))}
          </div>
        </div>
      </section>
    </>
  );
}

